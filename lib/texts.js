/** 128 = 10×12 + 8（推导值：改条数时这里会跟着变，不会变成一个对不上的魔法数） */
export const TEXT_TOTAL =
  LEVEL_TEXTS.reduce((sum, group) => sum + group.length, 0) + COOLING_TEXTS.length

/** 等级上限 = 文本组数（取样时把等级钳进 [1, MAX_LEVEL]） */
const MAX_LEVEL = LEVEL_TEXTS.length

/**
 * 非法等级归一：<1 ⇒ 1，>10 ⇒ 10（`Infinity` 也按 10），非整数 ⇒ 截断后同样钳制。
 * 非数字（`undefined` / `NaN` / 字符串 / 对象）一律按 1 处理——
 * 宁可让新存档显示最保守的 L1 文本，也不抛错（取样必须在任何畸形状态下都能出一句）。
 */
function normalizeLevel(level) {
  if (typeof level !== 'number' || Number.isNaN(level)) return 1
  if (!(level >= 1)) return 1
  const n = Math.trunc(level)
  return n > MAX_LEVEL ? MAX_LEVEL : n
}

/**
 * `rand()` 的结果 → `[0, length)` 的下标（均匀分布，且**绝不会越界**）。
 * 注入的随机源是测试用的，可能返回 1、负数、NaN 这类越界值：全部钳回合法区间
 * （1 回落到 0，保证 `pick` 永远只差一次 `rand()` 调用、不会因取整越界而重试或返回 undefined）。
 */
function randomIndex(rand, length) {
  const raw = typeof rand === 'function' ? Number(rand()) : Number.NaN
  const r = Number.isFinite(raw) && raw > 0 ? raw : 0
  const bounded = r < 1 ? r : 0.9999999999999999
  return Math.floor(bounded * length)
}

/**
 * 通用取样：在 `list` 里**均匀随机**取一条，且结果 ≠ `last`（相邻去重）。
 *
 * - `last` 为 `undefined` 或不在 `list` 里 ⇒ 正常在整表里取（不惩罚"第一次显示"和
 *   "上次那组已不在候选池"的情况，例如升级后 last 来自更高等级——事实上不会发生，但不赌）；
 * - `last` 命中时把这一条（连同其重复项）从候选里剔除后再取：**一次 `rand()` 出结果**，
 *   绝不"抽到 last 就重抽"（无限循环的风险在实现上就不存在）；
 * - 候选只剩 1 条时直接返回它（任一级候选数 ≥12，正常不会走到，但不能死循环）；
 * - 空表返回 `''`（纯防御，正常不会发生）。
 *
 * 单独导出是为了让测试能直接钉住"候选只剩一条"这条守卫；扩展侧只用下面两个具名取样函数。
 */
export function pickFromList(list, last, rand = Math.random) {
  if (!Array.isArray(list) || list.length === 0) return ''
  if (list.length === 1) return list[0]
  const candidates = list.includes(last) ? list.filter((text) => text !== last) : list
  if (candidates.length === 1) return candidates[0]
  return candidates[randomIndex(rand, candidates.length)]
}

/**
 * 等级文本取样（design D-5：`pool(level) = L1..L{level} 的并集`，第 N 级 = N×12 条）。
 *
 * 第 N 级只看得到 L1..LN（spec Requirement 1：MUST NOT 显示 L(N+1)），
 * 且**均匀随机**——低等级文本在高等级仍会出现（"高等级可见低等级文本"scenario），
 * 不做等级加权（design D-5 被否决的备选①）。相邻去重由 `pickFromList` 负责。
 *
 * @param {number} level 当前等级（1..10；越界或非数字自动钳制）
 * @param {string} [last] 上一次显示的文本（相邻去重）
 * @param {() => number} [rand] 随机源，默认 `Math.random`；测试可注入确定性实现
 */
export function pickFavorText(level, last, rand = Math.random) {
  const pool = LEVEL_TEXTS.slice(0, normalizeLevel(level)).flat()
  return pickFromList(pool, last, rand)
}

/**
 * 点击冷却文本取样（spec Requirement 3）：在 8 条冷却文本里均匀随机、
 * 与 `last` 相邻去重；**与等级无关**（第 1 级与第 10 级看到的是同一个集合）。
 */
export function pickCoolingText(last, rand = Math.random) {
  return pickFromList(COOLING_TEXTS, last, rand)
}
